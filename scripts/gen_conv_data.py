#!/usr/bin/env python3
"""Generate the convolution test data and an independent golden reference.

28x28 feature map (12-bit signed activations), one 5x5 kernel (8-bit signed weights),
valid convolution -> 24x24 outputs, 20-bit wrap-around accumulation (as mac_opiso).
The data is deterministic and contains: ~40 % zero activations (ReLU-like sparsity),
an all-zero region, saturating +2047 / -2048 regions whose sums overflow 20 bits,
and the extreme weights -128 / +127.

usage: gen_conv_data.py <out.h>
"""
import random
import sys

H = W = 28
K = 5
OH, OW = H - K + 1, W - K + 1


def wrap20(x):
    x &= 0xFFFFF
    return x - (1 << 20) if x & 0x80000 else x


rng = random.Random(2026)
w = [rng.randint(-64, 127) for _ in range(K * K)]   # positive bias -> large sums
w[0], w[12], w[24] = -128, 127, -128

a = [[0 if rng.random() < 0.4 else rng.randint(-2048, 2047) for _ in range(W)] for _ in range(H)]
for y in range(0, 9):
    for x in range(0, 9):
        a[y][x] = 2047                                  # positive overflow region
for y in range(19, 28):
    for x in range(19, 28):
        a[y][x] = -2048                                 # negative overflow region
for y in range(10, 18):
    for x in range(0, 10):
        a[y][x] = 0                                     # fully sparse windows

ref, raw = [], []
for oy in range(OH):
    for ox in range(OW):
        s = sum(a[oy + ky][ox + kx] * w[ky * K + kx] for ky in range(K) for kx in range(K))
        raw.append(s)
        ref.append(wrap20(s))

zeros = sum(v == 0 for row in a for v in row)
wrapped = sum(r != s for r, s in zip(ref, raw))
zero_windows = sum(all(a[oy + ky][ox + kx] == 0 for ky in range(K) for kx in range(K))
                   for oy in range(OH) for ox in range(OW))
assert wrapped > 0 and zero_windows > 0, "test data must exercise wrap-around and sparsity"


def rows(vals, per=16):
    return ",\n".join("  " + ", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


flat = [v for row in a for v in row]
with open(sys.argv[1], "w", newline="\n") as f:
    f.write(f"""/* Generated by scripts/gen_conv_data.py (seed 2026). Do not edit. */
#ifndef CONV_DATA_H
#define CONV_DATA_H
#include <stdint.h>

#define CONV_IN_H {H}
#define CONV_IN_W {W}
/* zero activations: {zeros}/{H * W}; outputs whose sum wraps 20 bits: {wrapped}/{OH * OW};
   all-zero windows: {zero_windows} */

static const int16_t conv_in[{H * W}] = {{
{rows(flat)}
}};

static const int8_t conv_w[{K * K}] = {{
{rows(w)}
}};

static const int32_t conv_ref[{OH * OW}] = {{
{rows(ref, 12)}
}};

#endif
""")
print(f"gen_conv_data: {H}x{W} input, {zeros} zero activations, "
      f"{wrapped} wrapped outputs, {zero_windows} all-zero windows -> {sys.argv[1]}")
